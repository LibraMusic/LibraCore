//go:build ignore

package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"github.com/spf13/pflag"

	"github.com/libramusic/libracore/tools/dbgen"
)

const defaultTemplatesDir = "../tools/dbgen/templates"

func main() {
	var templatesDir string
	pflag.StringVar(
		&templatesDir,
		"templates-dir",
		"",
		"Path to templates directory (defaults to "+defaultTemplatesDir+" relative to working directory)",
	)
	pflag.Parse()

	wd, err := os.Getwd()
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error getting working directory: %v\n", err)
		os.Exit(1)
	}

	if templatesDir == "" {
		templatesDir = filepath.Join(wd, defaultTemplatesDir)
	}

	if _, err := os.Stat(templatesDir); os.IsNotExist(err) {
		fmt.Fprintf(os.Stderr, "Expected templates directory not found: %s\n", templatesDir)
		os.Exit(1)
	}

	entities := dbgen.AllEntities()

	var userEntity dbgen.EntityDef
	for _, e := range entities {
		if e.Name == "User" {
			userEntity = e
			break
		}
	}

	// Template functions common to all templates.
	funcMap := template.FuncMap{
		"join": func(items []string, sep string) string {
			return strings.Join(items, sep)
		},
		"columnNames": func(cols []dbgen.ColumnDef) []string {
			names := make([]string, len(cols))
			for i, c := range cols {
				names[i] = c.DBName
			}
			return names
		},
		"prefixedColumns": func(cols []dbgen.ColumnDef, prefix string) []string {
			names := make([]string, len(cols))
			for i, c := range cols {
				names[i] = prefix + c.DBName
			}
			return names
		},
		"fieldRefs": func(cols []dbgen.ColumnDef) []string {
			refs := make([]string, len(cols))
			for i, c := range cols {
				refs[i] = "&item." + c.Name
			}
			return refs
		},
		"userFieldRefs": func(cols []dbgen.ColumnDef) []string {
			refs := make([]string, len(cols))
			for i, c := range cols {
				refs[i] = "&user." + c.Name
			}
			return refs
		},
		"add": func(a, b int) int { return a + b },
		"dict": func(values ...interface{}) map[string]interface{} {
			m := make(map[string]interface{})
			for i := 0; i+1 < len(values); i += 2 {
				m[values[i].(string)] = values[i+1]
			}
			return m
		},
		"sub": func(a, b int) int { return a - b },
		"until": func(n int) []int {
			res := make([]int, n)
			for i := 0; i < n; i++ {
				res[i] = i
			}
			return res
		},
	}

	entries, err := os.ReadDir(templatesDir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error reading templates directory: %v\n", err)
		os.Exit(1)
	}

	var templateFiles []string
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		if !strings.HasSuffix(entry.Name(), ".tmpl") || strings.HasPrefix(entry.Name(), "_") {
			continue
		}
		templateFiles = append(templateFiles, filepath.Join(templatesDir, entry.Name()))
	}

	if len(templateFiles) == 0 {
		fmt.Fprintf(os.Stderr, "No .tmpl files found in %s\n", templatesDir)
		os.Exit(1)
	}

	data := map[string]interface{}{
		"Entities":   entities,
		"UserEntity": userEntity,
	}

	dbDir := wd

	commonContent, err := os.ReadFile(filepath.Join(templatesDir, "_common.tmpl"))
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error reading common template: %v\n", err)
		os.Exit(1)
	}

	for _, tmplPath := range templateFiles {
		tmplName := strings.TrimSuffix(filepath.Base(tmplPath), ".tmpl")

		tmplContent, err := os.ReadFile(tmplPath)
		if err != nil {
			fmt.Fprintf(os.Stderr, "Error reading template %s: %v\n", tmplPath, err)
			os.Exit(1)
		}

		tmpl := template.Must(template.New(tmplName).Funcs(funcMap).Parse(string(commonContent)))
		tmpl = template.Must(tmpl.Parse(string(tmplContent)))

		var buf bytes.Buffer
		if err := tmpl.Execute(&buf, data); err != nil {
			fmt.Fprintf(os.Stderr, "Error executing template %s: %v\n", tmplPath, err)
			os.Exit(1)
		}

		code, err := format.Source(buf.Bytes())
		if err != nil {
			fmt.Fprintf(os.Stderr, "Error formatting code from template %s: %v\n", tmplPath, err)
			os.Exit(1)
		}

		header := []byte("// Code generated by dbgen. DO NOT EDIT.\n\n")
		code = append(header, code...)

		outputPath := filepath.Join(dbDir, tmplName+"_gen.go")
		if err := os.WriteFile(outputPath, code, 0o644); err != nil {
			fmt.Fprintf(os.Stderr, "Error writing file %s: %v\n", outputPath, err)
			os.Exit(1)
		}
		fmt.Printf("Generated %s\n", outputPath)
	}
}
